#!/usr/bin/env node
/**
 * Build assets/nws-office-names.json -- the "The National Weather Service in <office>" names
 * WarnGen prints, so the Decoder's mock NWS text style words offices exactly like WarnGen.
 *
 *   node tools/build-nws-office-names.mjs           rewrite the file
 *   node tools/build-nws-office-names.mjs --check   fail if the file is out of date
 *
 * Source of truth: OFFICE_LABELS and NORMALIZED_OFFICE_LABELS_ONLY in warngen/index.html,
 * read as text (the page is never executed). The name follows WarnGen's getOfficeMeta():
 * drop the 4-letter call sign and a trailing 2-letter state, then apply the normalized
 * override. Overrides are kept verbatim (DMX keeps its archived trailing space).
 */

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const ROOT = path.resolve(import.meta.dirname, '..');
const SOURCE = path.join(ROOT, 'warngen', 'index.html');
const TARGET = path.join(ROOT, 'assets', 'nws-office-names.json');

function readTable(html, name) {
    const start = html.indexOf('var ' + name + ' = {');
    if (start < 0) throw new Error(`${name} not found in warngen/index.html`);
    const end = html.indexOf('\n            }', start);
    if (end < 0) throw new Error(`${name} has no closing brace`);
    const table = {};
    const entry = /^\s*([A-Z]{3}):\s*"([^"]*)",?\s*(?:\/\/.*)?$/;
    for (const line of html.slice(start, end).split('\n').slice(1)) {
        if (!line.trim()) continue;
        const match = entry.exec(line);
        if (!match) throw new Error(`${name}: cannot read line ${JSON.stringify(line.trim())}`);
        table[match[1]] = match[2];
    }
    if (!Object.keys(table).length) throw new Error(`${name} is empty`);
    return table;
}

export function officeLocation(label) {
    if (!/^[A-Z]{4} /.test(label)) return label;
    return label.slice(5).replace(/\s+[A-Z]{2}$/, '');
}

export function buildOfficeNames(html) {
    const labels = readTable(html, 'OFFICE_LABELS');
    const normalized = readTable(html, 'NORMALIZED_OFFICE_LABELS_ONLY');
    const offices = {};
    for (const id of Object.keys(labels).sort()) offices[id] = normalized[id] ?? officeLocation(labels[id]);
    for (const id of Object.keys(normalized)) {
        if (!(id in labels)) throw new Error(`NORMALIZED_OFFICE_LABELS_ONLY has ${id}, which OFFICE_LABELS lacks`);
    }
    return {
        _comment: 'Generated by tools/build-nws-office-names.mjs from WarnGen (warngen/index.html OFFICE_LABELS + NORMALIZED_OFFICE_LABELS_ONLY). Do not edit by hand.',
        offices,
    };
}

function main() {
    const text = JSON.stringify(buildOfficeNames(fs.readFileSync(SOURCE, 'utf8')), null, 4) + '\n';
    if (process.argv.includes('--check')) {
        const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
        if (current !== text) {
            console.error('assets/nws-office-names.json is out of date; run node tools/build-nws-office-names.mjs');
            process.exit(1);
        }
        console.log('assets/nws-office-names.json is current.');
        return;
    }
    fs.writeFileSync(TARGET, text);
    console.log(`Wrote assets/nws-office-names.json (${Object.keys(JSON.parse(text).offices).length} offices).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) main();
